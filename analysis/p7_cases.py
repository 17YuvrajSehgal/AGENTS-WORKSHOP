"""Case-study numbers for the paper, read straight from measure.json medians.

  python -I analysis/p7_cases.py   -> paper/cases.tex
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
F = ROOT / "data" / "p7_paper" / "fetched"
# macro prefix -> (pr id, [(macro suffix, signal), ...])
CASES = {
    "caseA": (3731932011, [("Wall", "wall_s"), ("Sys", "sys_s"), ("Syscalls", "syscalls"),
                           ("Pread", "sc:pread64"), ("Bytes", "bytes_read"),
                           ("Task", "task-clock"), ("Threads", "threads")]),
    "caseB": (3814494025, [("Wall", "wall_s"), ("Getdents", "sc:getdents64"), ("Instr", "instructions")]),
    "caseC": (3466077419, [("Wall", "wall_s"), ("Instr", "instructions")]),
    "caseD": (3728179568, [("Wall", "wall_s"), ("Offcpu", "offcpu_ns_main"), ("Migr", "cpu-migrations"), ("Futex", "futex_ns")]),
}


def med(xs):
    s = sorted(xs)
    n = len(s)
    return s[n // 2] if n % 2 else (s[n // 2 - 1] + s[n // 2]) / 2


def fmt(x):
    return f"{x:.2f}" if x < 100 and x != int(x) else f"{x:,.0f}"


def series(v, k):  # same as p7_results.series
    if k == "syscalls":
        cols = [x for n, x in v.items() if n.startswith("sc:") and n != "sc:stat_any"]
        return [sum(c[i] for c in cols) for i in range(len(cols[0]))]
    return [x for x in v[k] if x is not None]


out = ["% generated by analysis/p7_cases.py; do not edit"]
for pre, (pid, sigs) in CASES.items():
    mp = next(p for p in F.glob(f"*/*_{pid}/measure.json"))
    var = json.loads(mp.read_text())["variants"]
    for suf, k in sigs:
        b, h = series(var["base"], k), series(var["head"], k)
        sep = max(h) < min(b) or min(h) > max(b)
        assert sep, (pid, k)  # every case number must be fully separated
        r = med(h) / med(b)
        out.append(f"\\newcommand{{\\{pre}{suf}}}{{{r:.2f}$\\times$}}")
        out.append(f"\\newcommand{{\\{pre}{suf}Base}}{{{fmt(med(b))}}}")
        out.append(f"\\newcommand{{\\{pre}{suf}Head}}{{{fmt(med(h))}}}")
(ROOT / "paper" / "cases.tex").write_text("\n".join(out) + "\n")
print("\n".join(out))
